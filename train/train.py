"""Train the Reactive Sentinel anomaly MLP and emit a fixed-point Solidity library.

Features (each scaled to 0..1, then x10_000 on-chain):
  f0 amount_ratio   - withdrawal amount / vault balance before withdrawal (capped at 1)
  f1 new_recipient  - 1 if this recipient was never paid by the vault before
  f2 recency        - 1 - min(seconds_since_last / 3600, 1)  (1 = right after the previous one)
  f3 velocity       - min(withdrawals_in_last_hour / 10, 1)
Output: logit; > 0 means "freeze".
"""
import pathlib
import numpy as np

rng = np.random.default_rng(7)
N = 40_000
SCALE = 10_000
HIDDEN = 8


def sample(n):
    amount = rng.beta(1.2, 6.0, n)
    big = rng.random(n) < 0.15
    amount[big] = rng.uniform(0.4, 1.0, big.sum())
    new = (rng.random(n) < 0.3).astype(float)
    recency = rng.beta(1.0, 3.0, n)
    burst = rng.random(n) < 0.1
    recency[burst] = rng.uniform(0.85, 1.0, burst.sum())
    velocity = np.clip(rng.poisson(1.2, n) / 10.0, 0, 1)
    velocity[burst] = np.clip(velocity[burst] + rng.uniform(0.3, 0.7, burst.sum()), 0, 1)
    x = np.stack([amount, new, recency, velocity], axis=1)
    # Ground-truth policy a human security reviewer would apply, plus label noise.
    risk = (
        3.2 * amount
        + 1.6 * new * amount * 2
        + 1.4 * recency * velocity * 2
        + 0.8 * new * recency
        - 2.6
    )
    y = (risk + rng.normal(0, 0.25, n) > 0).astype(float)
    return x, y


x, y = sample(N)
xv, yv = sample(8_000)

w1 = rng.normal(0, 0.5, (4, HIDDEN))
b1 = np.zeros(HIDDEN)
w2 = rng.normal(0, 0.5, (HIDDEN, 1))
b2 = np.zeros(1)


def forward(inp):
    h = np.maximum(0, inp @ w1 + b1)
    return h, (h @ w2 + b2).ravel()


lr = 0.05
for epoch in range(400):
    idx = rng.permutation(N)
    for start in range(0, N, 512):
        bi = idx[start:start + 512]
        xb, yb = x[bi], y[bi]
        h, logit = forward(xb)
        p = 1 / (1 + np.exp(-logit))
        g = (p - yb)[:, None] / len(bi)
        gw2 = h.T @ g
        gb2 = g.sum(0)
        gh = (g @ w2.T) * (h > 0)
        gw1 = xb.T @ gh
        gb1 = gh.sum(0)
        w2 -= lr * gw2; b2 -= lr * gb2; w1 -= lr * gw1; b1 -= lr * gb1

_, lv = forward(xv)
float_acc = ((lv > 0) == (yv > 0.5)).mean()

# Quantize: inputs and first-layer weights x SCALE -> hidden in SCALE^2 -> rescale to SCALE.
qw1 = np.round(w1 * SCALE).astype(int)
qb1 = np.round(b1 * SCALE * SCALE).astype(int)
qw2 = np.round(w2.ravel() * SCALE).astype(int)
qb2 = int(np.round(b2[0] * SCALE * SCALE))


def qscore(fx):
    xi = np.round(fx * SCALE).astype(np.int64)
    h = np.maximum(0, xi @ qw1 + qb1) // SCALE
    return h @ qw2 + qb2


q_acc = ((np.array([qscore(r) for r in xv]) > 0) == (yv > 0.5)).mean()
print(f"positives {y.mean():.3f}  float acc {float_acc:.4f}  quantized acc {q_acc:.4f}")

lines = []
lines.append("// SPDX-License-Identifier: MIT")
lines.append("// AUTO-GENERATED by train/train.py - do not edit by hand.")
lines.append("pragma solidity ^0.8.29;")
lines.append("")
lines.append("/// @title SentinelMLP: 4-8-1 ReLU network, fixed point (inputs scaled by 1e4).")
lines.append(f"/// @notice Validation accuracy: float {float_acc:.4f}, quantized {q_acc:.4f} on 8,000 synthetic withdrawals.")
lines.append("library SentinelMLP {")
lines.append("    int256 internal constant SCALE = 10_000;")
lines.append("")
lines.append("    /// @return logit Positive means anomalous (freeze).")
lines.append("    function score(int256[4] memory x) internal pure returns (int256 logit) {")
lines.append("        int256 h;")
lines.append(f"        logit = {qb2};")
for j in range(HIDDEN):
    terms = " + ".join(f"({qw1[i, j]}) * x[{i}]" for i in range(4))
    lines.append(f"        h = ({terms} + ({qb1[j]})) / SCALE;")
    lines.append(f"        if (h > 0) logit += h * ({qw2[j]});")
lines.append("    }")
lines.append("}")
out = pathlib.Path(__file__).resolve().parent.parent / "contracts" / "SentinelMLP.sol"
out.write_text("\n".join(lines) + "\n")

# Golden vectors for the Solidity tests.
cases = [
    ("routine small payment", [0.05, 0.0, 0.1, 0.1]),
    ("drain to new address", [0.95, 1.0, 0.2, 0.1]),
    ("rapid burst", [0.3, 0.0, 0.98, 0.8]),
    ("big but known recipient", [0.45, 0.0, 0.05, 0.0]),
]
for name, c in cases:
    print(f"{name:26s} {c} -> {int(qscore(np.array(c)))}")
